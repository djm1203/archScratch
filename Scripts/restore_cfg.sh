#!/usr/bin/env bash
# archScratch - deploy dotfiles (symlinks with backup)

source "$(dirname "$0")/global_fn.sh"

BACKUP_DIR="$HOME/.config-backup-$(date +%Y%m%d-%H%M%S)"

backup_file() {
    # Move a real file/dir (or foreign symlink) into the timestamped backup dir.
    local target="$1"
    mkdir -p "$BACKUP_DIR"
    mv --backup=numbered "$target" "$BACKUP_DIR/"
    print_warn "Backed up $target → $BACKUP_DIR/"
}

backup_and_link() {
    local src="$1"   # source file/dir in repo
    local dest="$2"  # destination path

    # Never create a dangling symlink to a missing source.
    if [[ ! -e "$src" ]]; then
        print_err "Source missing, skipping: $src"
        return 1
    fi

    if [[ -L "$dest" ]]; then
        # If the existing symlink already points into this repo, just refresh it;
        # otherwise it's the user's own link — preserve it by backing it up.
        local cur
        cur="$(readlink -f "$dest" 2>/dev/null)"
        if [[ "$cur" == "$(readlink -f "$DOTFILES_DIR")"/* ]]; then
            rm -f "$dest"
        else
            backup_file "$dest"
        fi
    elif [[ -e "$dest" ]]; then
        backup_file "$dest"
    fi

    mkdir -p "$(dirname "$dest")"
    ln -sf "$src" "$dest"
    print_ok "Linked $dest"
}

deploy_configs() {
    print_header "Deploying ~/.config dotfiles"
    local cfg="$DOTFILES_DIR/Configs"
    local d
    for d in hypr waybar foot kitty wofi mako nvim fastfetch gtk-3.0 gtk-4.0 \
             qt5ct qt6ct waypaper zathura theme; do
        backup_and_link "$cfg/$d" "$HOME/.config/$d"
    done
}

deploy_qt_colors() {
    print_header "Installing qt5ct/qt6ct Gruvbox color scheme"
    local src="$DOTFILES_DIR/Configs/qt-colors/gruvbox.conf" d
    if [[ ! -f "$src" ]]; then
        print_warn "Missing $src — skipping Qt color scheme"
        return 0
    fi
    for d in qt5ct qt6ct; do
        sudo install -Dm644 "$src" "/usr/share/$d/colors/gruvbox.conf"
    done
    print_ok "Qt color scheme installed"
}

deploy_machine_conf() {
    # ~/.config/hypr is a symlink into the repo, so write the machine-specific
    # Lua module there; it's gitignored, regenerated on every deploy, and loaded
    # by hyprland.lua (Hyprland >= 0.57 reads Lua, not hyprland.conf).
    print_header "Generating machine-specific Hyprland config"
    local out="$DOTFILES_DIR/Configs/hypr/machine.lua"
    rm -f "$DOTFILES_DIR/Configs/hypr/machine.conf"   # legacy hyprlang file, no longer read

    # Detect an NVIDIA GPU by PCI vendor (0x10de) — works before drivers load.
    local has_nvidia=false
    if grep -qli '^0x10de' /sys/bus/pci/devices/*/vendor 2>/dev/null        || lspci 2>/dev/null | grep -qi nvidia; then
        has_nvidia=true
    fi

    local is_thinkpad=false
    grep -qi thinkpad /sys/class/dmi/id/product_family /sys/class/dmi/id/product_version 2>/dev/null && is_thinkpad=true

    {
        echo "-- Generated by restore_cfg.sh — regenerated on every deploy, do not edit."
        if [[ "$has_nvidia" == "true" ]]; then
            cat <<'EOF'
-- NVIDIA GPU detected (https://wiki.hypr.land/Nvidia/)
hl.env("NVD_BACKEND", "direct")
hl.config({ cursor = { no_hardware_cursors = 1 } })
-- Uncomment if the desktop renders on the dGPU (mux/dGPU-only mode):
-- hl.env("LIBVA_DRIVER_NAME", "nvidia")
-- hl.env("__GLX_VENDOR_LIBRARY_NAME", "nvidia")
EOF
        else
            echo "-- No NVIDIA GPU detected — nothing machine-specific needed."
        fi
        if [[ "$is_thinkpad" == "true" ]]; then
            cat <<'EOF'
-- ThinkPad: Intel VA-API driver + TrackPoint. The device name must match `hyprctl devices`
-- (T480: tpps/2-elan-trackpoint); a wrong name is harmless but does nothing.
hl.env("LIBVA_DRIVER_NAME", "iHD")
hl.device({
    name          = "tpps/2-elan-trackpoint",
    sensitivity   = 0.3,
    accel_profile = "flat",
    scroll_method = "on_button_down",
    scroll_button = 274,
})
EOF
        fi
    } > "$out"
    print_ok "machine.lua generated (NVIDIA: $has_nvidia, ThinkPad: $is_thinkpad)"
}

deploy_local_bin() {
    print_header "Deploying ~/.local/bin scripts"
    mkdir -p "$HOME/.local/bin"
    shopt -s nullglob
    local script name
    for script in "$DOTFILES_DIR/local-bin/"*; do
        name="$(basename "$script")"
        chmod +x "$script"   # no-op when already +x in the repo (keeps git clean)
        backup_and_link "$script" "$HOME/.local/bin/$name"
    done
    shopt -u nullglob
}

deploy_home_files() {
    print_header "Deploying home dotfiles"
    backup_and_link "$DOTFILES_DIR/home/.zshrc" "$HOME/.zshrc"
}

deploy_wallpapers() {
    print_header "Setting up wallpapers"
    mkdir -p "$HOME/Pictures/Wallpapers"
    shopt -s nullglob
    local wp name count=0
    for wp in "$DOTFILES_DIR/Wallpapers/"*; do
        name="$(basename "$wp")"
        if [[ ! -e "$HOME/Pictures/Wallpapers/$name" ]]; then
            cp -r "$wp" "$HOME/Pictures/Wallpapers/$name" && count=$((count + 1))
        fi
    done
    shopt -u nullglob
    print_ok "Wallpapers ready in ~/Pictures/Wallpapers/ ($count new)"
}

deploy_systemd_user() {
    print_header "Deploying systemd user units"
    local src="$DOTFILES_DIR/Configs/systemd/user"
    [[ -d "$src" ]] || { print_warn "No systemd user units to deploy"; return 0; }
    mkdir -p "$HOME/.config/systemd/user"
    shopt -s nullglob
    local unit name
    for unit in "$src"/*; do
        name="$(basename "$unit")"
        backup_and_link "$unit" "$HOME/.config/systemd/user/$name"
    done
    shopt -u nullglob
    systemctl --user daemon-reload 2>/dev/null || true
    if systemctl --user enable --now wallpaper-rotate.timer 2>/dev/null; then
        print_ok "wallpaper-rotate.timer enabled"
    else
        print_warn "Could not enable wallpaper-rotate.timer now (it will start on next login)"
    fi
}

deploy_greetd() {
    print_header "Configuring greetd"
    local cfg="$DOTFILES_DIR/system/greetd-config.toml"
    local dest="/etc/greetd/config.toml"
    if sudo cmp -s "$cfg" "$dest"; then
        print_ok "greetd config already up to date"
        return 0
    fi
    sudo mkdir -p /etc/greetd
    if [[ -e "$dest" ]]; then
        sudo cp "$dest" "${dest}.archscratch-bak.$(date +%Y%m%d-%H%M%S)"             && print_warn "Backed up existing $dest"
    fi
    sudo install -Dm644 "$cfg" "$dest"
    print_ok "greetd configured (tuigreet)"
}

deploy_greetd_keyring() {
    # Unlock gnome-keyring with the login password (Proton VPN, Discord, Evolution need it).
    local pam=/etc/pam.d/greetd
    [[ -f "$pam" ]] || return 0
    grep -q pam_gnome_keyring "$pam" && return 0
    {
        echo "auth       optional     pam_gnome_keyring.so"
        echo "session    optional     pam_gnome_keyring.so auto_start"
    } | sudo tee -a "$pam" >/dev/null && print_ok "greetd PAM: gnome-keyring unlock enabled"
}

deploy_zram() {
    print_header "Configuring zram swap"
    local cfg="$DOTFILES_DIR/system/zram-generator.conf"
    local dest="/etc/systemd/zram-generator.conf"
    if sudo cmp -s "$cfg" "$dest"; then
        print_ok "zram-generator config already up to date"
        return 0
    fi
    sudo install -Dm644 "$cfg" "$dest" && print_ok "zram-generator configured (active next boot)"
}

deploy_thinkpad() {
    grep -qi thinkpad /sys/class/dmi/id/product_family /sys/class/dmi/id/product_version 2>/dev/null || return 0
    print_header "ThinkPad tuning (TLP thresholds, touchpad rate)"
    local pair src dest
    for pair in "tlp-thinkpad.conf:/etc/tlp.d/01-archscratch.conf" "psmouse.conf:/etc/modprobe.d/psmouse.conf"; do
        src="$DOTFILES_DIR/system/${pair%%:*}"; dest="${pair#*:}"
        cmp -s "$src" "$dest" 2>/dev/null || sudo install -Dm644 "$src" "$dest"
    done
    sudo tlp start >/dev/null 2>&1 || true
    print_ok "ThinkPad config installed (touchpad rate applies after reboot)"
}

main() {
    deploy_configs
    if command -v envsubst &>/dev/null; then
        # Run via bash: deploy_local_bin (which chmods +x) hasn't run yet, so
        # don't depend on the repo file's exec bit.
        bash "$DOTFILES_DIR/local-bin/theme-switch" --init || print_err "theme-switch --init FAILED: bar/launcher/terminal colors will be missing"
    else
        print_err "envsubst (gettext) missing: run 'pacman -S gettext' then 'theme-switch --init'"
    fi
    deploy_qt_colors
    deploy_machine_conf
    deploy_local_bin
    deploy_home_files
    deploy_wallpapers
    deploy_systemd_user
    deploy_greetd
    deploy_greetd_keyring
    deploy_zram
    deploy_thinkpad
    print_ok "All dotfiles deployed"
    [[ -d "$BACKUP_DIR" ]] && print_warn "Backups saved to: $BACKUP_DIR"
}

main "$@"
